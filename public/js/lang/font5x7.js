export const GLYPH_W = 5;
export const GLYPH_H = 7;

/** @param {string} ch @returns {string[]} */
export function glyph(ch) {
  const key = ch.toUpperCase();
  return GLYPHS[key] || GLYPHS['?'];
}

/** 文本渲染后的像素宽度 @param {string} s @param {number} scale */
export function textWidth(s, scale = 1) {
  if (!s.length) return 0;
  return (s.length * (GLYPH_W + 1) - 1) * scale;
}

/** 文本渲染后的像素高度 */
export function textHeight(scale = 1) {
  return GLYPH_H * scale;
}
